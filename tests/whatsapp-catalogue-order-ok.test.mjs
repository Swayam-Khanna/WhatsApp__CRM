import { describe, it } from 'node:test';
import assert from 'node:assert/strict';
import {
  evaluateWhatsAppOrderWorkflow,
  getCustomerOrderDraft,
  saveCustomerOrderDraft,
  parseStructuredCatalogueOrder,
} from '../backend/lib/whatsapp-order-service.server.ts';
import { getAuthoritativeCrmProducts } from '../backend/lib/product-registry.ts';
import { classifyCustomerIntent, extractEntities } from '../backend/lib/message-understanding.server.ts';
import { getStoredOrders } from '../backend/lib/crm-store.server.ts';

describe('WHATSAPP CATALOGUE ORDER AND "OK" CONFIRMATION TEST SUITE', () => {
  const testPhone = `9170184${String(Date.now()).slice(-5)}`;

  it('1. Parses exact structured catalogue order generated by catalogue button', async () => {
    const catalogue = await getAuthoritativeCrmProducts();
    const catalogMsg = `🌿 *NEW ORDER • PRAJNAA HIMALAYAN HARVEST* 🌿
--------------------------------------
👤 *Customer:* Rajat Test
📞 *Phone:* +91 70184 90629
--------------------------------------
🛒 *ORDERED ITEMS (3 items):*
1. *Pahari Spiced Kadak Chai Masala* (150g Jar)
   • Qty: 1 × ₹260 = ₹260

2. *Pahari House Garam Masala* (200g Jar)
   • Qty: 1 × ₹320 = ₹320

3. *Stone-Ground Lakadong Turmeric* (250g Jar)
   • Qty: 1 × ₹240 = ₹240
--------------------------------------
💰 *Grand Total:* ₹820
📦 *Fulfillment:* Shipping (Solan Hub, HP)
--------------------------------------
Namaste ji! Kripya mera order confirm kar dijiye and payment & dispatch details bhej dijiye.`;

    const parsed = parseStructuredCatalogueOrder(catalogMsg, catalogue);
    assert.ok(parsed, 'Catalogue order should be parsed successfully');
    assert.equal(parsed.items.length, 3);
    assert.equal(parsed.grandTotal, 820);
    assert.equal(parsed.customerName, 'Rajat Test');
  });

  it('2. Catalogue order without address prompts for delivery address', async () => {
    const catalogMsg = `🌿 *NEW ORDER • PRAJNAA HIMALAYAN HARVEST* 🌿
--------------------------------------
👤 *Customer:* Rajat Test
📞 *Phone:* +91 70184 90629
--------------------------------------
🛒 *ORDERED ITEMS (3 items):*
1. *Pahari Spiced Kadak Chai Masala* (150g Jar)
   • Qty: 1 × ₹260 = ₹260

2. *Pahari House Garam Masala* (200g Jar)
   • Qty: 1 × ₹320 = ₹320

3. *Stone-Ground Lakadong Turmeric* (250g Jar)
   • Qty: 1 × ₹240 = ₹240
--------------------------------------
💰 *Grand Total:* ₹820
📦 *Fulfillment:* Shipping (Solan Hub, HP)
--------------------------------------
Namaste ji! Kripya mera order confirm kar dijiye and payment & dispatch details bhej dijiye.`;

    const res = await evaluateWhatsAppOrderWorkflow({
      customerPhone: testPhone,
      customerText: catalogMsg,
      customerName: 'Rajat Test',
      messageId: `wamid_cat_${Date.now()}`,
    });

    assert.equal(res.isOrderWorkflow, true);
    assert.ok(res.replyText?.includes('delivery address aur 6-digit PIN code'));

    const draft = await getCustomerOrderDraft(testPhone);
    assert.ok(draft, 'Draft should be saved');
    assert.equal(draft.items.length, 3);
    assert.equal(draft.stage, 'awaiting_address');
  });

  it('3. Customer provides address: draft notes address and asks for confirmation', async () => {
    const res = await evaluateWhatsAppOrderWorkflow({
      customerPhone: testPhone,
      customerText: 'Mall Road, Shimla, Himachal Pradesh 171001',
      customerName: 'Rajat Test',
      messageId: `wamid_addr_${Date.now()}`,
    });

    assert.equal(res.isOrderWorkflow, true);
    assert.ok(res.replyText?.includes('Mall Road, Shimla'));
    assert.ok(res.replyText?.includes('Kya main aapka yeh order confirm kar doon'));

    const draft = await getCustomerOrderDraft(testPhone);
    assert.ok(draft.deliveryAddress);
    assert.equal(draft.stage, 'awaiting_confirmation');
  });

  it('4. Customer types "ok": automatically books order with unique ORD-2026-XXXX ID', async () => {
    const res = await evaluateWhatsAppOrderWorkflow({
      customerPhone: testPhone,
      customerText: 'ok',
      customerName: 'Rajat Test',
      messageId: `wamid_ok_${Date.now()}`,
    });

    assert.equal(res.isOrderWorkflow, true);
    assert.equal(res.orderCreated, true);
    assert.ok(res.order, 'Order object must be returned');
    assert.match(res.order.orderNumber, /^ORD-\d{4}-\d{4}$/);
    assert.equal(res.order.amount, 820);
    assert.ok(res.replyText?.includes(res.order.orderNumber));
    assert.ok(res.replyText?.includes('confirm ho gaya hai'));

    // Check store
    const stored = getStoredOrders().find((o) => o.orderNumber === res.order.orderNumber);
    assert.ok(stored, 'Order must be saved in CRM orders');
  });

  it('5. "want to order some products" does NOT extract "#some" as order number', async () => {
    const catalogue = await getAuthoritativeCrmProducts();
    const entities = extractEntities('want to order some products', catalogue);
    assert.equal(entities.orderNumber, undefined, 'orderNumber must NOT be "some"');

    const intent = classifyCustomerIntent('want to order some products', { language: 'en', messageCount: 1 }, entities, catalogue);
    assert.equal(intent.intent, 'order_placement');
    assert.notEqual(intent.intent, 'order_status');
  });

  it('6. "i want to create a neew ordeer" is recognized as order_placement, not unclear handoff', async () => {
    const catalogue = await getAuthoritativeCrmProducts();
    const entities = extractEntities('i want to create a neew ordeer', catalogue);
    const intent = classifyCustomerIntent('i want to create a neew ordeer', { language: 'en', messageCount: 1 }, entities, catalogue);
    assert.equal(intent.intent, 'order_placement');
    assert.notEqual(intent.intent, 'human_handoff');
  });
});
